// sortRowsByFirstColumn keeps output stable: several of these results come from
// a map, whose iteration order would otherwise vary run to run.
func sortRowsByFirstColumn(rows [][]any) {
	for i := 1; i < len(rows); i++ {
		for j := i; j > 0 && rowKey(rows[j]) < rowKey(rows[j-1]); j-- {
			rows[j], rows[j-1] = rows[j-1], rows[j]
		}
	}
}

func rowKey(row []any) string {
	if len(row) == 0 {
		return ""
	}
	return fmt.Sprintf("%v|%v", row[0], row[min(1, len(row)-1)])
}

