// runProviderAllocationSet replaces the consumer's allocations wholesale, which
// is what placement's PUT does — there is no incremental form.
func runProviderAllocationSet(ctx context.Context, client *gophercloud.ServiceClient, o *output.Options,
	consumer string, f *allocationSetFlags, w io.Writer,
) error {
	if err := o.CheckColumns(allocationColumns...); err != nil {
		return err
	}
	// Placement 1.38 made consumer_type required, and it is not a value koc can
	// invent on the operator's behalf — it describes what the consumer *is*. Say
	// so here rather than letting placement answer with a schema dump.
	if f.consumerType == "" && placementapi.RequiresConsumerType(client.Microversion) {
		return fmt.Errorf("placement %s and later require a consumer type: pass --consumer-type "+
			"(e.g. INSTANCE or MIGRATION)", placementapi.ConsumerTypeMicroversion)
	}
	byProvider := map[string]allocations.ProviderAllocationsOpts{}
	for _, spec := range f.specs {
		provider, resources, err := parseAllocationSpec(spec)
		if err != nil {
			return fmt.Errorf("parsing --allocation: %w", err)
		}
		existing, ok := byProvider[provider]
		if !ok {
			existing = allocations.ProviderAllocationsOpts{Resources: map[string]int{}}
		}
		for class, amount := range resources {
			existing.Resources[class] = amount
		}
		byProvider[provider] = existing
	}
	opts := allocations.UpdateOpts{
		Allocations:  byProvider,
		ProjectID:    f.projectID,
		UserID:       f.userID,
		ConsumerType: f.consumerType,
	}
	if err := placementapi.UpdateAllocations(ctx, client, consumer, opts); err != nil {
		return err
	}
	return runProviderAllocationShow(ctx, client, o, consumer, w)
}

// parseAllocationSpec parses "rp=<uuid>,VCPU=2,MEMORY_MB=1024" into a provider
// and its resource amounts.
func parseAllocationSpec(spec string) (string, map[string]int, error) {
	var provider string
	resources := map[string]int{}
	for _, part := range strings.Split(spec, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		k, v, ok := strings.Cut(part, "=")
		if !ok {
			return "", nil, fmt.Errorf("expected key=value in %q", spec)
		}
		if k == "rp" {
			provider = v
			continue
		}
		n, err := strconv.Atoi(v)
		if err != nil {
			return "", nil, fmt.Errorf("%s in %q: %w", k, spec, err)
		}
		resources[k] = n
	}
	if provider == "" {
		return "", nil, fmt.Errorf("%q is missing rp=<provider-uuid>", spec)
	}
	if len(resources) == 0 {
		return "", nil, fmt.Errorf("%q names no resource amounts", spec)
	}
	return provider, resources, nil
}

