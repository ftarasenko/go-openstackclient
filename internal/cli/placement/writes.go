// resourceQuery renders --resource values into placement's `resources` query
// parameter, which spells each entry CLASS:amount.
//
// The CLI spelling is CLASS=amount, matching upstream osc-placement
// (`--resource <resource_class>=<value>`). Passing that through untranslated is
// what placement rejects with:
//
//	Badly formed resources parameter. Expected resources query string parameter
//	in form: ?resources=VCPU:2,MEMORY_MB:1024. Got: VCPU=1.
//
// The colon form is accepted too, since it is what the wire wants and operators
// who read the error message reach for it.
func resourceQuery(resources []string) (string, error) {
	parts := make([]string, 0, len(resources))
	for _, r := range resources {
		class, amount, ok := strings.Cut(r, "=")
		if !ok {
			if class, amount, ok = strings.Cut(r, ":"); !ok {
				return "", fmt.Errorf("expected CLASS=amount, got %q", r)
			}
		}
		class, amount = strings.TrimSpace(class), strings.TrimSpace(amount)
		if class == "" || amount == "" {
			return "", fmt.Errorf("expected CLASS=amount, got %q", r)
		}
		parts = append(parts, class+":"+amount)
	}
	return strings.Join(parts, ","), nil
}

type candidateListFlags struct {
	resources []string
	required  []string
	memberOf  []string
	limit     int
}

func newAllocationCandidateCommand(a *auth.Options, o *output.Options) *cobra.Command {
	f := &candidateListFlags{}
	list := &cobra.Command{
		Use:   "list",
		Short: "List providers that can satisfy a resource request",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if err := o.Validate(); err != nil {
				return err
			}
			ctx := cmd.Context()
			client, err := newPlacementClient(ctx, a)
			if err != nil {
				return err
			}
			return runAllocationCandidateList(ctx, client, o, f, cmd.OutOrStdout())
		},
	}
	fl := list.Flags()
	fl.StringArrayVar(&f.resources, "resource", nil, "required amount as CLASS=amount, e.g. VCPU=2 (repeatable)")
	fl.StringArrayVar(&f.required, "required", nil, "trait the provider must have; prefix ! to forbid (repeatable)")
	fl.StringArrayVar(&f.memberOf, "member-of", nil, "aggregate UUID the provider must belong to (repeatable)")
	fl.IntVar(&f.limit, "limit", 0, "maximum number of candidates to return")
	_ = list.MarkFlagRequired("resource")

	cmd := &cobra.Command{Use: "candidate", Short: "Inspect placement allocation candidates"}
	cmd.AddCommand(list)
	return cmd
}

func runAllocationCandidateList(ctx context.Context, client *gophercloud.ServiceClient, o *output.Options,
	f *candidateListFlags, w io.Writer,
) error {
	// Placement takes the amounts as one comma-separated `resources` parameter,
	// not as repeated ones, and separates class from amount with a colon.
	query, err := resourceQuery(f.resources)
	if err != nil {
		return fmt.Errorf("parsing --resource: %w", err)
	}
	opts := allocationcandidates.ListOpts{
		Resources: query,
		Required:  f.required,
		MemberOf:  f.memberOf,
		Limit:     f.limit,
	}
	candidates, err := placementapi.ListAllocationCandidates(ctx, client, opts)
	if err != nil {
		return err
	}
	t := output.Table{Columns: []string{"Resource Provider", colResourceClass, "Capacity", "Used"}}
	for providerID, summary := range candidates.ProviderSummaries {
		for class, res := range summary.Resources {
			t.Rows = append(t.Rows, []any{providerID, class, res.Capacity, res.Used})
		}
	}
	sortRowsByFirstColumn(t.Rows)
	return o.WriteList(w, t)
}

